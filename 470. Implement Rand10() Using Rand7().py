class Solution:
    def rand10(self):
        """
        :rtype: int
        """
        while True:
            # Генерируем число в диапазоне [1, 49], используя rand7() дважды
            num = (rand7() - 1) * 7 + rand7()

            # Отбрасываем числа вне диапазона [1, 40]
            if num <= 40:
                break

        # Возвращаем число в диапазоне [1, 10], используя модуль
        return num % 10 + 1

# Для реализации rand10() с использованием функции rand7(), я генерирую равномерно распределённое
# случайное число в диапазоне [1, 49] путём комбинирования двух вызовов rand7(). Использую формулу
# (rand7() - 1) * 7 + rand7(), которая даёт число от 1 до 49. Далее я отбрасываю числа, попадающие
# в диапазон [41, 49], чтобы избежать неравномерного распределения при взятии остатка по модулю 10.
# Когда число попадает в диапазон [1, 40], я возвращаю его остаток от деления на 10 плюс 1, чтобы
# получить равномерное распределение в диапазоне [1, 10]. Этот метод гарантирует равномерное
# распределение результатов и работает эффективно, минимизируя количество вызовов rand7().